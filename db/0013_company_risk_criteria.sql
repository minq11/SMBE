-- 회사의 위험성 수준 판단 기준.
--
-- 지금까지는 평가할 때마다 `risk_assessments.criteria_snapshot` 에 직접 타이핑했다.
-- 그러면 같은 회사인데 표준서마다 기준이 다르게 적힐 수 있고, 감사에서 "귀사의 판단
-- 기준은 무엇입니까"에 한 문서로 답할 수 없다. 위험성평가는 사업주가 기준을 정해 두고
-- 그 기준에 따라 실시하는 구조이므로 기준의 원본은 회사에 있어야 한다.
--
--   companies.risk_criteria          원본 — 회사정보에서 수정
--   risk_assessments.criteria_snapshot  사본 — 평가 생성 시 복사 (그대로 유지)
--
-- 사본은 없애지 않는다. 회사가 나중에 기준을 바꿔도 이미 승인된 평가는 그때의 기준으로
-- 남아야 한다. 컬럼 이름이 `_snapshot` 인 것이 원래 그 의도였고, 빠져 있던 원본을 채운다.
--
-- 등급 수(상·중·하 3단계)는 `risk_assessment_items.initial_risk_level` 의 CHECK 로
-- 고정돼 있다. 회사가 정하는 것은 단계 수가 아니라 각 단계의 정의와 허용 가능 경계다.

-- 기본 문구를 컬럼 기본값으로 둔다. 기존 회사와 앞으로 만들 회사가 같은 출발점을 갖고,
-- 각자 회사정보에서 자기 기준으로 고쳐 쓴다.
ALTER TABLE companies
  ADD COLUMN risk_criteria text NOT NULL DEFAULT
    '상: 사망 또는 신체 일부를 잃을 수 있는 재해가 발생할 수 있음
중: 치료가 필요한 부상이 발생할 수 있음
하: 응급처치로 회복 가능한 경미한 부상에 그침

허용 가능: 하. 중은 감소대책을 적용한 뒤 허용 가능. 상은 허용하지 않음.';
