-- 알림 받을 메일 주소를 로그인 계정의 메일과 분리한다.
--
-- users.email 은 소셜 로그인에서 따라온 **계정 정보**다. 부분 유일 인덱스가
-- 걸려 있고, 다른 provider 로 같은 메일이 오면 병합하지 않고 비워 두는 규칙이
-- 여기에 매여 있다. 사람이 마음대로 고칠 수 있는 값이 아니다.
--
-- 그런데 현장에서 지시서·승인요청·회의 알림을 받는 주소는 카카오 로그인에
-- 딸려온 주소가 아니라 회사 메일인 경우가 많다. 그래서 **받을 주소**를 따로
-- 둔다. 비어 있으면 계정 메일로 보내므로(COALESCE), 기존 사용자는 아무것도
-- 달라지지 않는다.
--
-- 유일 제약을 걸지 않는다. 현장 한 곳이 대표 메일 하나를 같이 쓰는 경우가
-- 있고, 그걸 막을 이유가 없다.
ALTER TABLE users
  ADD COLUMN contact_email citext;

COMMENT ON COLUMN users.contact_email IS
  '알림을 받을 주소. 비어 있으면 email(로그인 계정 메일)로 보낸다.';
